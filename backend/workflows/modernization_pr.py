"""Push a converted codebase to a branch and let the customer's CI compile it.

Nothing on this platform builds the converted code. Building customer source on the API
host is arbitrary code execution, and a real build needs the real SDK and a package
restore, so D-05 sends real builds to the customer's CI instead. The consequence, until
this existed, was that a type error in generated C# reached the *customer* rather than the
agent: reconciliation catches every cross-file failure visible without compiling, and
nothing caught the rest (C-42). A run could look finished and not build.

So this workflow makes the customer's own GitHub Actions runner the compiler. It commits
the converted tree plus `.github/workflows/modernization-build.yml`, which builds the
branch and POSTs the compiler output back to `POST /runs/{id}/build-results` — where the
existing ingest maps each diagnostic to the unit that produced the file and sets it back
to `ready`, so the claim loop re-converts it. No new execution model, no new
infrastructure.

Two properties of that CI job are load-bearing, and both are counter-intuitive enough to
be commented in the YAML itself:

- it must NOT stop at a failing build — a failing build is the payload, not an error;
- the log must be JSON-encoded by a tool, not by the shell — a compiler message containing
  a quote or a backslash otherwise yields invalid JSON, and that failure is silent.

Failure policy differs from `autofix_pr` on purpose. Its guards return a `reason` because
there is an earlier code review worth handing back regardless. Here there is no partial
result to preserve — a run with no artifacts, and a missing GitHub token, are both caller
errors — so they raise `ValueError`, which the route should surface as a 400.

No LLM call happens here, so the workflow takes no budget reservation and meters nothing.
"""
import logging
from typing import Any, Dict, List, Optional

import httpx

from backend import config
from backend.services.modernization import reconcile, store
from backend.workflows.base import ProgressReporter, Step

logger = logging.getLogger(__name__)

WORKFLOW_ID = "modernization-pr"

BUILD_WORKFLOW_PATH = ".github/workflows/modernization-build.yml"

# One branch per run, derived from the run id rather than its name: the branch has to stay
# stable across build/fix rounds (round two commits to the same branch, which re-triggers
# the same workflow and updates the same PR), and a run id needs no slug sanitising.
BRANCH_PREFIX = "lm-modernization/"

ALL_STEPS: tuple = (
    "Collect converted files",
    "Commit to branch",
    "Open pull request",
    "Record branch and PR on the run",
)

# The CI job reads the platform token from this repository secret. The name appears in the
# generated YAML; the value never does, and never passes through this process at all.
TOKEN_SECRET_NAME = "MODERNIZATION_TOKEN"

_MISSING_TOKEN = (
    "GITHUB_TOKEN is not configured (backend/config.py reads it from the environment). "
    "Opening a modernization PR needs a fine-grained PAT with BOTH 'Contents: Read and "
    "Write' (to push the converted tree) and 'Pull requests: Read and Write' (to open the "
    "PR) on the target repository."
)


def branch_for(run_id: str) -> str:
    """The branch a run's conversion is pushed to. Stable for the life of the run."""
    return f"{BRANCH_PREFIX}{run_id}"


def plan_steps() -> List[Step]:
    """Every step always runs; the list exists so a route can size its job record with
    `count_steps(plan_steps())` rather than hardcoding a number that drifts."""
    return [(label, True) for label in ALL_STEPS]


# ── The CI workflow ────────────────────────────────────────────────────────

# Placeholders are sentinels rather than `str.format` / f-string fields because the YAML is
# full of `${{ ... }}` and `${...}`, which both of those would try to interpret. Escaping
# every one of them is precisely the kind of quiet corruption this file exists to prevent.
# Raw string: the shell line continuations below must survive as backslash + newline.
_BUILD_WORKFLOW_TEMPLATE = r"""# Generated by the LM AI-SDLC ReviewOps Agent for modernization run __LM_RUN_ID__.
#
# The platform never compiles the converted code — this job is the compiler. It builds the
# branch and posts every diagnostic back, which is how a type error becomes the agent's
# problem instead of the reviewer's.
name: Modernization build

on:
  push:
    branches:
      - '__LM_BRANCH_GLOB__'
  workflow_dispatch:

# Read-only: this job reports, it never writes to the repository.
permissions:
  contents: read

jobs:
  build:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4

      - uses: actions/setup-dotnet@v4
        with:
          dotnet-version: '__LM_DOTNET_VERSION__'

      # `continue-on-error` on both build steps, and `if: always()` on the report step
      # below. A workflow that stops at the first failing step never reports the errors it
      # found, which defeats the entire point of this file — the failing build IS the
      # payload. All output, stdout and stderr, goes to one log.
      - name: Restore
        continue-on-error: true
        run: |
          set -o pipefail
          dotnet restore 2>&1 | tee -a build.log

      - name: Build
        id: build
        continue-on-error: true
        run: |
          set -o pipefail
          dotnet build --no-restore -warnaserror:none 2>&1 | tee -a build.log
          # Recorded because "the compiler ran and said nothing" and "the compiler never
          # ran" are different reports, and only this step can tell them apart.
          echo "exit_code=$?" >> "$GITHUB_OUTPUT"

      - name: Report diagnostics to LM AI-SDLC
        if: always()
        env:
          # Read from a repository secret into the environment and used only as the
          # `X-API-Key` header. It is never echoed, never written to build.log, and no token
          # value appears anywhere in this file.
          #
          # An API key rather than a JWT, and that is not interchangeable: `get_caller`
          # accepts either, but a bearer token is a JWT with an expiry. Stored as a
          # repository secret it would work for as long as the token lived and then start
          # returning 401 — and a build callback that silently stops arriving looks exactly
          # like a build that stopped failing.
          MODERNIZATION_TOKEN: ${{ secrets.__LM_TOKEN_SECRET__ }}
          LM_CALLBACK_URL: '__LM_CALLBACK_URL__'
          LM_RUN_ID: '__LM_RUN_ID__'
          LM_BUILD_EXIT: ${{ steps.build.outputs.exit_code }}
        run: |
          set -euo pipefail
          if [ -z "${MODERNIZATION_TOKEN:-}" ]; then
            echo "Add the platform token as the repository secret __LM_TOKEN_SECRET__." >&2
            exit 1
          fi
          # This step also runs when checkout or setup-dotnet failed, so build.log may not
          # exist. That case must NOT be reported as a clean build: an empty log means the
          # compiler never ran, and recording it as "passed" would wipe the error
          # fingerprint the platform uses to detect a rework loop that is not converging.
          # Saying so in the log itself makes the distinction survive the round trip.
          touch build.log
          if [ ! -s build.log ]; then
            echo "MSBUILD : error LMBUILD001: the build produced no output at all -" \
                 "the job failed before dotnet build ran (checkout or setup-dotnet)." \
                 >> build.log
          fi
          # Keep the tail. The error summary MSBuild prints last is the part worth having,
          # and an unbounded log is a request body nothing should have to accept.
          tail -c 1000000 build.log > build.tail.log
          # `jq -Rs` reads the whole log as one raw string and does the JSON escaping
          # itself. Interpolating the log into a shell heredoc instead would break on any
          # compiler message containing a quote or a backslash — and that failure is
          # silent and confusing: the POST is rejected as malformed and the build looks
          # like it simply never reported.
          #
          # `diagnostics: []` alongside the log when the compiler exited 0. That is the
          # positive claim "it built cleanly", which an empty parse of the log alone cannot
          # distinguish from "nothing was parseable".
          if [ "${LM_BUILD_EXIT:-1}" = "0" ]; then EXTRA='{diagnostics: []}'; else EXTRA='{}'; fi
          jq -Rs \
            --arg run_id "$LM_RUN_ID" \
            --arg branch "$GITHUB_REF_NAME" \
            --arg commit_sha "$GITHUB_SHA" \
            "{run_id: \$run_id, source: \"github_actions\", branch: \$branch,
              commit_sha: \$commit_sha, command: \"dotnet build\", log: .} + $EXTRA" \
            < build.tail.log > payload.json
          curl --silent --show-error --fail-with-body \
            --request POST "$LM_CALLBACK_URL" \
            --header "X-API-Key: $MODERNIZATION_TOKEN" \
            --header "Content-Type: application/json" \
            --data-binary @payload.json

      # Regardless of outcome: when the callback itself fails, this artifact is the only
      # copy of what the compiler said.
      - name: Upload build log
        if: always()
        uses: actions/upload-artifact@v4
        with:
          name: modernization-build-log
          path: build.log
          if-no-files-found: warn
"""


def _yaml_scalar(value: str, label: str, require_url: bool = False) -> str:
    """Check a value can sit inside a single-quoted YAML scalar, or raise.

    Rejected, not escaped. Everything interpolated here is a URL, a run id or a version
    string — none of which legitimately contains whitespace or a quote — and a value that
    needed escaping would be a caller sending something this function was never meant to
    carry into a file the customer's CI executes.
    """
    text = (value or "").strip()
    if not text:
        raise ValueError(f"{label} is required to render the build workflow.")
    if any(ch.isspace() for ch in text) or "'" in text or '"' in text:
        raise ValueError(f"{label} must not contain whitespace or quotes: {text!r}")
    if require_url and not text.startswith(("http://", "https://")):
        raise ValueError(f"{label} must be an http(s) URL: {text!r}")
    return text


def render_build_workflow(callback_url: str, run_id: str, dotnet_version: str = "8.0.x") -> str:
    """The GitHub Actions workflow that builds the branch and reports back.

    `callback_url` is the run's `POST /runs/{id}/build-results` endpoint, fully qualified —
    the platform has no configured public base URL, so only the caller knows how the
    customer's CI can reach it.
    """
    return (
        _BUILD_WORKFLOW_TEMPLATE
        .replace("__LM_BRANCH_GLOB__", f"{BRANCH_PREFIX}**")
        .replace("__LM_TOKEN_SECRET__", TOKEN_SECRET_NAME)
        .replace("__LM_CALLBACK_URL__", _yaml_scalar(callback_url, "callback_url", require_url=True))
        .replace("__LM_RUN_ID__", _yaml_scalar(run_id, "run_id"))
        .replace("__LM_DOTNET_VERSION__", _yaml_scalar(dotnet_version, "dotnet_version"))
    )


# ── The PR body ────────────────────────────────────────────────────────────

def build_pr_body(run: Dict[str, Any], reconciliation: Dict[str, Any], artifact_count: int) -> str:
    """The PR description a human opens this branch onto.

    It leads with what the branch is, because the failure mode this product has to design
    against is a reviewer treating machine output as reviewed code. Everything below that
    is either a number the platform actually measured or a thing the reviewer has to do.
    """
    stats = run.get("stats") or {}
    counts = (reconciliation or {}).get("counts") or {}
    redactions = run.get("redactions") or []

    source = run.get("source_language") or "the legacy source"
    target = run.get("target_stack") or "the target stack"

    lines = [
        f"## Machine conversion of {run.get('name') or 'a legacy codebase'} — not reviewed code",
        "",
        f"An automated run converted {source} to {target}. **No human has read this code, "
        "and nothing in it has been compiled.** It is a starting point for a port, not a "
        "finished one — review it as you would review a first draft written by someone who "
        "has never seen the rest of your system.",
        "",
        "| | |",
        "|---|---|",
        f"| Source | {source} |",
        f"| Target | {target} |",
        f"| Source files ingested | {stats.get('files_ingested', 'unknown')} |",
        f"| Components converted | {counts.get('components', 'unknown')} |",
        f"| Files in this PR | {artifact_count} |",
        f"| Run id | `{run.get('id', '')}` |",
        "",
    ]

    lines += ["### What the consistency pass found", ""]
    if (reconciliation or {}).get("issues"):
        # Reuse the renderer the checkpoint and the export report already use, rather than
        # keeping a second one here that can drift from it.
        lines += [reconcile.describe(reconciliation), ""]
    elif reconciliation:
        lines += ["No cross-file inconsistencies were found. That is not the same as "
                  "\"it builds\" — nothing was compiled.", ""]
    else:
        lines += ["This run has not been reconciled, so the cross-file checks "
                  "(duplicate types, namespace drift, orphaned output, entry-point "
                  "coverage) have not run over it.", ""]

    lines += ["### Secrets removed before conversion", ""]
    if redactions:
        # Locations only. The values were replaced at ingest and were never stored, so
        # there is nothing here to leak — and nothing that would justify printing it into a
        # pull request if there were.
        lines.append(
            f"{len(redactions)} secret(s) were redacted from the source before any of it "
            "reached a model, so the converted code carries placeholders where they were. "
            "Re-supply each from your own secret store — the locations, and nothing else, "
            "are listed below."
        )
        lines.append("")
        for hit in redactions[:20]:
            category = hit.get("category") or "secret"
            lines.append(f"- `{hit.get('path', '')}` line {hit.get('line', 0)} ({category})")
        if len(redactions) > 20:
            lines.append(f"- … and {len(redactions) - 20} more")
    else:
        lines.append("No secrets were detected in the source during ingest.")
    lines.append("")

    lines += [
        "### `// MIGRATION-BLOCKED:` markers",
        "",
        "Any `// MIGRATION-BLOCKED:` marker in this diff is a deliberate refusal to convert "
        "something dangerous, not an omission — the converter found source it could not "
        "translate without silently dropping behaviour (a dynamic `eval`, a variable "
        "variable, a dynamic include) and said so instead of guessing. Each one must be "
        "resolved by a human. Deleting the marker without replacing the behaviour it "
        "describes is how the behaviour disappears for good.",
        "",
        "### What a reviewer must check by hand",
        "",
        "- **Behaviour, not shape.** Nothing here was tested against the legacy system. "
        "Compare against what the old code *did*, including its bugs, where those were relied on.",
        "- **Every `// MIGRATION-BLOCKED:` marker.** See above.",
        "- **Configuration and secrets.** Placeholders replace redacted values; connection "
        "strings, keys and endpoints are yours to fill in.",
        "- **Data access and schema.** The conversion follows the charter's decision about "
        "the database's fate; confirm that is still what you want against real data.",
        "- **Authentication and authorization.** Legacy auth rarely maps cleanly. Check the "
        "converted checks are equivalent, not merely present.",
        "- **Anything the consistency pass flagged above**, which is where cross-file "
        "breakage shows up first.",
        "",
        "### Build results",
        "",
        f"This PR includes `{BUILD_WORKFLOW_PATH}`. It runs `dotnet restore` and "
        "`dotnet build` on every push to this branch and posts the compiler output back to "
        "the platform automatically, so the build result arrives without anyone copying it "
        f"anywhere — it needs the `{TOKEN_SECRET_NAME}` repository secret (a platform **API "
        f"key**, not a login token — an expiring token would make the callbacks stop "
        f"arriving, which looks the same as a build that stopped failing). Errors reopen the "
        f"units that produced the offending files, and the run re-converts them.",
        "",
        "---",
        "*Opened by [LM AI-SDLC ReviewOps Agent](https://learnedmachine.ai).*",
    ]
    return "\n".join(lines)


# ── The workflow ───────────────────────────────────────────────────────────

def run(
    orch,
    run_id: str,
    owner: str,
    repo: str,
    callback_url: str,
    base_branch: str = "",
    dotnet_version: str = "8.0.x",
    on_progress: Optional[Any] = None,
) -> Dict[str, Any]:
    """Commit a run's converted artifacts to a branch of `owner/repo` and open a PR.

    The target repository is named explicitly rather than derived from the run's
    `source_ref`: a PHP → .NET conversion usually belongs in a new repository, not on a
    branch of the legacy one, so inferring it would be wrong more often than right.

    `base_branch` empty lets `commit_tree` decide — the existing modernization branch if a
    previous round already created it, otherwise the repository's default branch.
    """
    mod_run = store.get_run(run_id)
    if not mod_run:
        raise ValueError(f"No modernization run with id '{run_id}'.")
    if not config.GITHUB_TOKEN:
        raise ValueError(_MISSING_TOKEN)

    progress = ProgressReporter(plan_steps(), on_progress)

    progress.step("Collect converted files")
    artifacts = store.list_artifacts(run_id, current_only=True, include_content=True)
    if not artifacts:
        raise ValueError(
            f"Run '{run_id}' has produced no converted files yet, so there is nothing to "
            f"open a pull request with. Its status is '{mod_run.get('status')}' at phase "
            f"'{mod_run.get('phase')}' — approve the plan gate and let the conversion run "
            f"before pushing it."
        )

    files = {a["path"]: (a.get("content") or "") for a in artifacts}
    # Assigned after the artifacts so the CI workflow always wins: a run that somehow
    # produced a file at this path must not be able to replace the thing that reports its
    # own build results.
    files[BUILD_WORKFLOW_PATH] = render_build_workflow(callback_url, run_id, dotnet_version)

    # Re-run rather than read back: the pass is deterministic and costs no model call, and
    # the report has to describe the artifacts going into *this* PR, not the ones a stored
    # report was written over.
    reconciliation = reconcile.run(run_id)
    branch = branch_for(run_id)

    progress.step("Commit to branch")
    # Artifact *content* never reaches a log line here or in commit_tree — it is converted
    # customer source.
    logger.info("Modernization run %s: committing %d file(s) to %s/%s:%s",
                run_id, len(files), owner, repo, branch)
    committed = orch.github.commit_tree(
        owner=owner, repo=repo, branch=branch, files=files,
        message=(
            f"Machine conversion: {mod_run.get('name') or run_id}\n\n"
            f"{len(artifacts)} converted file(s) plus the build-report workflow, from "
            f"modernization run {run_id}. Not reviewed, not compiled."
        ),
        base_branch=base_branch,
    )

    progress.step("Open pull request")
    body = build_pr_body(mod_run, reconciliation, len(artifacts))
    title = (f"Machine conversion: {mod_run.get('name') or run_id} → "
             f"{mod_run.get('target_stack') or 'target stack'}")
    pr: Dict[str, Any] = {}
    pr_exists = False
    try:
        pr = orch.github.create_pull_request(
            owner, repo, title=title, body=body,
            head=branch, base=committed["base_branch"],
        )
    except httpx.HTTPStatusError as exc:
        # Round two of the build/fix loop commits to the same branch, where a PR is already
        # open. That push is what re-triggers the build, so an existing PR is the expected
        # outcome, not a failure — anything else still raises.
        if not (exc.response.status_code == 422 and "already exist" in exc.response.text):
            raise
        pr_exists = True
        logger.info("Modernization run %s: PR for %s already open, updated by this push",
                    run_id, branch)

    progress.step("Record branch and PR on the run")
    # Both: the columns are what the next build round reads to know where to push, and the
    # event is the audit trail. Neither substitutes for the other — a column records the
    # current state, an event records that it changed and when.
    store.update_run(run_id, github_branch=branch, pr_url=pr.get("url", ""))
    store.append_event(
        run_id, "pull_request_opened" if not pr_exists else "pull_request_updated",
        f"{committed['files']} file(s) pushed to {owner}/{repo}:{branch} "
        f"({committed['commit_sha'][:7]}); {pr.get('url') or 'existing PR'}",
    )

    return {
        "run_id": run_id,
        "repo": f"{owner}/{repo}",
        "branch": branch,
        "base_branch": committed["base_branch"],
        "commit_sha": committed["commit_sha"],
        "files_committed": committed["files"],
        "build_workflow_path": BUILD_WORKFLOW_PATH,
        "token_secret_name": TOKEN_SECRET_NAME,
        "callback_url": callback_url,
        "pr_url": pr.get("url", ""),
        "pr_number": pr.get("number"),
        "pr_already_open": pr_exists,
        "reconciliation": reconciliation,
    }
