def _call(url, token, data=None, method="GET"):
    request = urllib.request.Request(
        url, data=json.dumps(data).encode("utf-8") if data is not None else None,
        method=method,
        headers={"Content-Type": "application/json", "X-API-Key": token})
    with urllib.request.urlopen(request, timeout=120) as response:
        return json.loads(response.read().decode("utf-8", "replace"))


def fetch_cases(token):
    url = "%s/runs/%s/parity-cases" % (API_BASE.rstrip("/"), RUN_ID)
    return _call(url, token).get("cases") or []


# -- Secrets -----------------------------------------------------------------------------
#
# A recorded request that still holds `password=__REDACTED_...__` cannot be replayed: sent
# as it stands the login fails, every page behind it redirects to the sign-in screen, and
# the report reads as a conversion that broke everything. So the value is supplied here, at
# replay time, on the machine that already has it.

def load_secrets(args):
    """--secret wins over --secrets-file, which wins over the environment.

    The file and environment paths exist because a value on a command line is visible to
    anyone who can list processes on this machine.
    """
    secrets = {}
    prefix = "LM_PARITY_SECRET_"
    for key, value in os.environ.items():
        if key.startswith(prefix):
            bare = key[len(prefix):].lower()
            secrets[bare] = value
            secrets[bare.replace("_", "-")] = value
    if args.secrets_file:
        with open(args.secrets_file, encoding="utf-8") as handle:
            raw = handle.read()
        try:
            for key, value in (json.loads(raw) or {}).items():
                secrets[str(key).strip().lower()] = str(value)
        except ValueError:
            for line in raw.splitlines():
                line = line.strip()
                if not line or line.startswith("#") or "=" not in line:
                    continue
                key, _, value = line.partition("=")
                secrets[key.strip().lower()] = value.strip()
    for item in args.secret or []:
        key, _, value = item.partition("=")
        if not key.strip():
            sys.stderr.write("Ignoring --secret %r: it has no name.\n" % item[:20])
            continue
        secrets[key.strip().lower()] = value
    return secrets


def _fill_field(text, slot, value, form_encoded):
    """Put `value` where this slot's placeholder sits, keeping the field's own encoding.

    Keyed by name first: two fields masked to the same placeholder token are two different
    secrets, and a blind token replace would fill both with whichever was supplied first.
    """
    placeholder = re.escape(slot["placeholder"])
    name = re.escape(slot["name"])
    encoded = urllib.parse.quote_plus(value, safe="")
    filled = re.sub(r"(^|[?&])(%s)=%s" % (name, placeholder),
                    lambda m: m.group(1) + m.group(2) + "=" + encoded, text)
    if filled != text:
        return filled
    filled = re.sub(r'("%s"\s*:\s*)"%s"' % (name, placeholder),
                    lambda m: m.group(1) + json.dumps(value), text)
    if filled != text:
        return filled
    # A placeholder sitting in free text -- a basic-auth blob, a bare token in a path.
    return text.replace(slot["placeholder"], encoded if form_encoded else value)


def apply_secrets(case, secrets):
    """-> (query, body, headers, filled names, the slots nobody supplied)."""
    query = case.get("query") or ""
    body = case.get("request_body") or ""
    headers = dict(case.get("request_headers") or {})
    form = "form-urlencoded" in (case.get("request_content_type") or "")
    filled, unfilled = [], []
    for slot in case.get("secret_slots") or []:
        value = secrets.get(slot["name"])
        if value is None:
            unfilled.append(slot)
            continue
        if slot.get("field") == "a request header":
            for key in list(headers):
                if key.strip().lower() == slot["name"]:
                    headers[key] = value
        elif slot.get("field") == "the query string":
            query = _fill_field(query, slot, value, True)
        else:
            body = _fill_field(body, slot, value, form)
        if slot["name"] not in filled:
            filled.append(slot["name"])
    return query, body, headers, filled, unfilled


def build_mask(cases, secrets):
    """{supplied value: the placeholder that stands for it} -- see `scrub`."""
    mask = {}
    for case in cases:
        for slot in case.get("secret_slots") or []:
            value = secrets.get(slot["name"])
            if value:
                mask.setdefault(value, slot["placeholder"])
    for value in secrets.values():
        if value:
            mask.setdefault(value, "__REDACTED_SUPPLIED__")
    return mask


def scrub(text, mask):
    """Put the placeholder back wherever a supplied value appears in a response.

    A page that redisplays what was posted would otherwise carry the credential back to the
    platform inside the observed body. The recorded side holds the placeholder, so putting
    the same one back is also what keeps the two comparable.
    """
    if not text:
        return text
    for value, placeholder in mask.items():
        if len(value) >= 4:
            text = text.replace(value, placeholder)
    return text


def replay_one(base_url, case, jar, secrets, mask):
    """Send one case at the converted app and report only what came back.

    No comparison happens here. A runner that decided pass/fail would be a second
    implementation of the comparator, and the two would disagree the first time either
    changed -- with the runner's answer being the one that reached the gate.
    """
    query, body, request_headers, filled, unfilled = apply_secrets(case, secrets)
    if unfilled:
        return {"case_id": case.get("id"),
                "error": "no value supplied for the secret(s) %s. Re-run with %s" % (
                    ", ".join("'%s' (%s)" % (s["name"], s["field"]) for s in unfilled),
                    " ".join("--secret %s=..." % s["name"] for s in unfilled)),
                "unfilled": [s["name"] for s in unfilled]}

    path = case.get("path") or "/"
    url = base_url.rstrip("/") + path + (("?" + query) if query else "")
    headers = {}
    for key, value in request_headers.items():
        headers[key] = value
    if case.get("request_content_type"):
        headers["Content-Type"] = case["request_content_type"]
    headers["Accept-Encoding"] = "identity"

    # One jar per group, so a case that depends on a prior POST sees the state that POST
    # created. Recorded cookie *values* are not replayed: the converted app issues its own
    # session, and pinning the legacy one would send an identifier it has never seen.
    if jar:
        headers["Cookie"] = "; ".join("%s=%s" % (k, v) for k, v in jar.items())

    started = time.time()
    request = urllib.request.Request(
        url, data=body.encode("utf-8") if body else None,
        method=case.get("method") or "GET", headers=headers)
    try:
        opener = urllib.request.build_opener(_NoRedirect)
        with opener.open(request, timeout=60) as response:
            status, raw = response.status, response.read()
            resp_headers = {k.lower(): v for k, v in response.headers.items()}
    except urllib.error.HTTPError as exc:
        status, raw = exc.code, exc.read()
        resp_headers = {k.lower(): v for k, v in (exc.headers or {}).items()}
    except Exception as exc:
        return {"case_id": case.get("id"), "error": "%s: %s" % (type(exc).__name__, exc),
                "duration_ms": int((time.time() - started) * 1000)}

    for cookie in resp_headers.get("set-cookie", "").split(","):
        pair = cookie.split(";")[0]
        if "=" in pair:
            k, _, v = pair.partition("=")
            jar[k.strip()] = v.strip()

    return {
        "case_id": case.get("id"),
        "status": status,
        "location": resp_headers.get("location", ""),
        "headers": {k: scrub(v, mask) for k, v in resp_headers.items()},
        "body": scrub(raw.decode("utf-8", "replace"), mask),
        "duration_ms": int((time.time() - started) * 1000),
        # Names only. This is what lets the platform judge a case whose recording was masked;
        # it never needs, and never receives, the value.
        "filled_secrets": filled,
    }


class _NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, *args, **kwargs):
        return None


def report_missing(cases, secrets):
    """-> {name: {fields}} for every secret this corpus needs and nobody supplied."""
    missing = {}
    for case in cases:
        for slot in case.get("secret_slots") or []:
            if slot["name"] not in secrets:
                missing.setdefault(slot["name"], set()).add(slot["field"])
    return missing


def main():
    parser = argparse.ArgumentParser(description="Replay parity cases against a converted app.")
    parser.add_argument("--base-url", required=True,
                        help="Where the converted application is running.")
    parser.add_argument("--token", required=True, help="An API key for the platform.")
    parser.add_argument("--secret", action="append", metavar="NAME=VALUE",
                        help="A credential that was masked out of the recording. Repeatable.")
    parser.add_argument("--secrets-file", default="",
                        help="A JSON object, or NAME=VALUE lines. Safer than --secret: a "
                             "command line is visible in a process listing.")
    parser.add_argument("--commit-sha", default="", help="Recorded alongside the report.")
    parser.add_argument("--dry-run", action="store_true",
                        help="Write parity-results.json instead of posting.")
    args = parser.parse_args()

    cases = fetch_cases(args.token)
    if not cases:
        sys.stderr.write("No parity cases are recorded for this run -- nothing to replay.\n")
        return 0
    secrets = load_secrets(args)
    mask = build_mask(cases, secrets)
    missing = report_missing(cases, secrets)
    if missing:
        sys.stderr.write(
            "\n%d credential(s) were masked out of this recording before it was stored, so "
            "the platform does not have them and neither does this script:\n\n" % len(missing))
        for name in sorted(missing):
            sys.stderr.write("  %-20s (%s)\n" % (name, ", ".join(sorted(missing[name]))))
        sys.stderr.write("\nRe-run with:\n\n  python %s --base-url %s --token ... %s\n\n"
                         % (os.path.basename(__file__), args.base_url,
                            " ".join("--secret %s=..." % n for n in sorted(missing))))
        sys.stderr.write("Cases needing them are reported as unrunnable rather than replayed "
                         "-- a request sent with a placeholder says nothing about the "
                         "conversion.\n\n")

    # Grouped and ordered: a CRUD flow is stateful, and "list employees" after "add" is a
    # different page from "list employees" before it.
    ordered = sorted(cases, key=lambda c: (c.get("group_name") or "", c.get("seq") or 0))
    results = []
    jars = {}
    blocked = {}
    for case in ordered:
        group = case.get("group_name") or ""
        jar = jars.setdefault(group, {})
        if group in blocked:
            # The whole reason this exists: one unreplayable sign-in was reported as
            # nineteen behavioural divergences, because every later case in its group ran
            # without a session and redirected to the login page.
            results.append({"case_id": case.get("id"),
                            "error": "an earlier case in this group (%s) could not be "
                                     "replayed, so this one would have run without the "
                                     "state it depends on" % blocked[group]})
            sys.stderr.write("  %s -> not run (the group's sign-in could not run)\n"
                             % case.get("name"))
            continue
        outcome = replay_one(args.base_url, case, jar, secrets, mask)
        if outcome.pop("unfilled", None):
            blocked[group] = case.get("name") or case.get("id")
        results.append(outcome)
        sys.stderr.write("  %s -> %s\n" % (case.get("name"),
                                           outcome.get("status") or outcome.get("error")))

    payload = {"results": results, "source": "__LM_SOURCE__",
               "base_url": args.base_url, "commit_sha": args.commit_sha}
    if args.dry_run:
        with open("parity-results.json", "w", encoding="utf-8") as handle:
            json.dump(payload, handle, indent=2)
        sys.stderr.write("Wrote parity-results.json -- nothing was posted.\n")
        return 0
    url = "%s/runs/%s/parity-results" % (API_BASE.rstrip("/"), RUN_ID)
    try:
        report = _call(url, args.token, payload, method="POST")
    except urllib.error.HTTPError as exc:
        sys.stderr.write("Posting the report failed (%s): %s\n"
                         % (exc.code, exc.read().decode("utf-8", "replace")[:2000]))
        return 1
    sys.stderr.write("\n%s\n" % json.dumps(report.get("counts") or report))
    # Exit non-zero on divergence so a CI step fails visibly. The platform has already
    # recorded the report either way; this only decides the colour of the build. A corpus
    # that could not run is non-zero too -- a replay nobody could perform must not read as a
    # replay that passed.
    counts = report.get("counts") or report
    return 1 if (counts.get("failed") or counts.get("errored") or missing) else 0


if __name__ == "__main__":
    sys.exit(main())
