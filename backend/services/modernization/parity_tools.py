def render_replayer(api_base: str, run_id: str, source: str = "external") -> str:
    """The replay runner, bound to one run. Runs wherever the converted app runs."""
    return (
        _REPLAYER_TEMPLATE
        .replace("__LM_API_BASE__", _literal(api_base, "api_base", require_url=True))
        .replace("__LM_RUN_ID__", _literal(run_id, "run_id"))
        .replace("__LM_SOURCE__", _literal(source, "source"))
    )


def render_readme(api_base: str, run_id: str, port: int = 8901) -> str:
    """What to do with the two scripts, for whoever opens the folder first."""
    return f"""# Behavioural parity for modernization run `{run_id}`

The conversion has been checked for whole files, cross-file consistency and — if you ran the
build workflow — that it compiles. None of that answers the question a customer actually
asks: **does it still do what the old system did?**

That question needs the old system. These two scripts are how it gets answered; both are
plain Python 3, standard library only.

## 1. Record what the legacy application does

Run this next to the legacy application. Nothing about it changes; the proxy sits in front.

    python {RECORDER_FILENAME} --target http://your-legacy-app --token YOUR_API_KEY

Then use the application through `http://127.0.0.1:{port}` as a user would. Walk the flows
that matter — **including the ones that fail**, because a 500 on a bad id is behaviour too,
and a conversion that turns it into a 200 has changed what callers see. Ctrl-C uploads.

Try `--dry-run` first if you want to read what would be sent before sending it.

### Before you point this at production

It records real responses, so it records whatever real data is on the pages you visit. Prefer
a staging copy. If it must be production, drive it with a test account, and know that the
platform scans uploads for credentials and masks them — but it cannot recognise your
customers' names.

## 2. Replay them against the converted application

Wherever the converted application runs — your CI, or a laptop:

    python {REPLAYER_FILENAME} --base-url http://localhost:5000 --token YOUR_API_KEY

It replays each case in its recorded order, posts what it observed, and exits non-zero if
anything diverged. It does not decide what "diverged" means: the platform compares, so that
the comparison exists in exactly one place.

### If you recorded a login

Anything that looked like a credential was masked out of the recording before it was stored,
so the platform does not have your password and cannot give it back. The replayer needs it:

    python {REPLAYER_FILENAME} --base-url http://localhost:5000 --token YOUR_API_KEY --secret password=the-one-you-used

Run it without the flag first and it will tell you exactly which names it wants. The value
goes from your machine to your application and nowhere else -- what gets reported back here
is the *name* of each secret that was filled, never the value. `--secrets-file` and
`LM_PARITY_SECRET_<NAME>` do the same thing without putting the value on a command line,
which anyone able to list processes on that machine can read.

A case whose credential nobody supplied is reported as **unrunnable**, never as a
difference -- and so is everything after it in the same journey, because a request sent
after a failed sign-in only proves that it was sent after a failed sign-in.

## What a divergence means

Not automatically that the conversion is wrong. It may be a case that recorded something
environmental, or a seed row that only exists in one database. The report names the legacy
file each case came from and the component that reimplemented it, so the question
"which part of the conversion changed behaviour" has an answer rather than a search.

A case is a claim about the old system, bugs included. If the legacy application numbers ids
in a way that collides after a delete, the converted one must do that too — a conversion that
quietly improves it has changed a behaviour someone may depend on. Fix such things
deliberately, afterwards, as their own change.
"""


def bundle(api_base: str, run_id: str, port: int = 8901,
           source: str = "external") -> Dict[str, str]:
    """Every parity file, keyed by the path it takes inside the exported tree."""
