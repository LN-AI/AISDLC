"""The two programs that feed parity, rendered for one run and handed to the customer.

`parity.py` stores golden cases and adjudicates replays, and deliberately executes nothing
(D-05). That leaves both ends of the loop unbuilt: something has to *watch* the legacy
application to produce cases, and something has to *replay* them against the converted one.
Neither can live here. So this module does what `modernization_pr.render_build_workflow`
already does for the compiler — it renders a program, and the customer runs it.

Why a recording proxy rather than a shim inside the legacy app
--------------------------------------------------------------
The obvious alternative for PHP is `auto_prepend_file` with a shutdown function. It was
rejected on three counts. It is PHP-only, and this pipeline converts Delphi, COBOL, Java and
C# too — parity is a claim about HTTP behaviour, not about a source language, so the recorder
should be as language-blind as the claim. It requires editing the configuration of an
application the customer is still running in production, which is a much larger ask than
"run this next to it for an afternoon". And it observes PHP's view of the response rather
than the bytes on the wire, which is the wrong side of the boundary: what a converted app has
to reproduce is what the *client* saw.

A proxy sees exactly what parity compares. It needs no change to the legacy application, and
if it dies the application keeps serving.

Why both programs are single-file and stdlib-only
-------------------------------------------------
Same reason the build workflow is a plain YAML file with `curl`: the customer runs it, on a
machine we have never seen, often on the old server the legacy app lives on. Every dependency
is a reason it does not get run. `http.server` and `urllib.request` are enough, and both
scripts are readable end to end by whoever is being asked to trust them with production
traffic — which someone should read before pointing it at a live system.

What the recorder refuses to capture
------------------------------------
Static assets. A stylesheet is not behaviour, and a corpus swamped by 200 image requests
reports parity on the parts nobody was worried about while hiding the four pages that matter.
Errors *are* captured: a 500 on a bad id is behaviour, and a conversion that turns it into a
200 has changed what callers see.

Sequencing. A CRUD flow is stateful — "add an employee" only means anything before "list
employees". The proxy groups by the client's session cookie and numbers within the group, and
the replayer replays a group in order through one cookie jar. Without that, a case that
depends on a prior POST fails against a correct conversion.
"""
import json
import re
from typing import Any, Dict

# One name for each generated file, used by the export, the API and the PR body alike so
# there is exactly one spelling of each.
RECORDER_FILENAME = "record_parity.py"
REPLAYER_FILENAME = "replay_parity.py"
PARITY_TOOLS_DIR = "parity"

_SAFE = re.compile(r"^[A-Za-z0-9:/?&=._~+-]+$")


def _literal(value: str, label: str, require_url: bool = False) -> str:
    """Check a value can sit inside a single-quoted Python literal, or raise.

    Rejected rather than escaped, exactly as `modernization_pr._yaml_scalar` argues: every
    value interpolated here is a URL, a run id or a token name, none of which legitimately
    contains a quote or whitespace. A value that *needed* escaping would be a caller carrying
    something unexpected into a file the customer is about to execute against production
    traffic, and the right answer to that is to stop.
    """
    text = (value or "").strip()
    if not text:
        raise ValueError(f"{label} is required to render the parity tools.")
    if not _SAFE.match(text):
        raise ValueError(f"{label} must be a plain token or URL with no quotes or "
                         f"whitespace: {text!r}")
    if require_url and not text.startswith(("http://", "https://")):
        raise ValueError(f"{label} must be an http(s) URL: {text!r}")
    return text


# ── The recorder ───────────────────────────────────────────────────────────────────────

_RECORDER_TEMPLATE = r'''#!/usr/bin/env python3
"""Record golden parity cases from the LEGACY application, for modernization run
__LM_RUN_ID__.

Generated by the LM AI-SDLC ReviewOps Agent. Standard library only — no pip install.

    python record_parity.py --target http://localhost:8080

Then use the legacy application through http://localhost:__LM_PORT__ exactly as a user
would: the flows you care about, including the ones that go wrong. Every page you visit is
recorded as "what the old system did". Press Ctrl-C to stop and upload.

READ THIS BEFORE POINTING IT AT PRODUCTION
------------------------------------------
This records real responses, so it records whatever real data is on the pages you visit. Use
a staging copy with representative-but-not-real data if you have one. If you must use
production, drive it with a test account and review what was captured: the upload is a plain
JSON file you can inspect with --dry-run first.
"""
import argparse
import http.server
import json
import re
import signal
import socketserver
import sys
import threading
import time
import urllib.error
import urllib.parse
import urllib.request

API_BASE = "__LM_API_BASE__"
RUN_ID = "__LM_RUN_ID__"

# A stylesheet is not behaviour. Recording them would swamp the corpus with requests nobody
# is worried about and bury the handful of pages that carry the logic.
SKIP_SUFFIXES = (".css", ".js", ".png", ".jpg", ".jpeg", ".gif", ".svg", ".ico",
                 ".woff", ".woff2", ".ttf", ".eot", ".map", ".webp", ".avif")
RECORD_TYPES = ("text/html", "application/json", "text/plain", "text/xml",
                "application/xml", "application/problem+json")

_lock = threading.Lock()
_cases = []
_seq = {}
# Cookie value -> the group it belongs to. See `_group_for`.
_cookie_group = {}
_visitors = [0]


def _cookie_values(cookie_header):
    return {part.partition("=")[2].strip()
            for part in (cookie_header or "").split(";") if "=" in part}


def _set_cookie_values(set_cookie_header):
    """The values a response assigns. Only the value; the name is not identity."""
    values = set()
    for chunk in (set_cookie_header or "").split(","):
        pair = chunk.split(";")[0]
        if "=" in pair:
            value = pair.partition("=")[2].strip()
            if value:
                values.add(value)
    return values


def _group_for(cookie_header, set_cookie_header):
    """One group per *browser*, following it across session-id changes.

    A group is a replay unit: the replayer keeps one cookie jar per group and sends the
    cases in `seq` order, so a case that depends on a prior POST sees the state that POST
    created. That only works if a whole journey lands in one group.

    Hashing the cookie header did not do that. **A correct application regenerates its
    session id when you log in** — it is the standard defence against session fixation — so
    the identifier before the login differs from the one after it, and the journey was cut in
    half at exactly the point that matters. Measured on a real recording: the login POST went
    into one group and the seventeen authenticated pages into another that contained no
    login, so replaying them could only ever produce seventeen redirects to the sign-in
    screen. Supplying the password does not fix that; the grouping has to.

    The proxy can see the seam, because it sees both sides: a response that *assigns* a
    cookie to a request that carried the old one is the same browser, continuing. So values
    are chained — old and new both map to the group, and the journey stays whole.

    Values are used as identity and nothing else. They are never sent anywhere, never
    stored, and never leave this process.
    """
    request_values = _cookie_values(cookie_header)
    response_values = _set_cookie_values(set_cookie_header)
    group = None
    for value in request_values:
        if value in _cookie_group:
            group = _cookie_group[value]
            break
    if group is None:
        if response_values or request_values:
            # A browser starting out: it arrives with nothing and leaves with a session.
            _visitors[0] += 1
            group = "visitor-%d" % _visitors[0]
        else:
            # No cookies in either direction. A stateless client, and correctly one group.
            return "anonymous"
    for value in request_values | response_values:
        _cookie_group[value] = group
    return group


def _should_record(path, content_type):
    lowered = path.split("?")[0].lower()
    if lowered.endswith(SKIP_SUFFIXES):
        return False
    essence = (content_type or "").split(";")[0].strip().lower()
    # An empty content-type on a redirect is normal and worth keeping: the Location header is
    # the whole behaviour of a POST-redirect-GET.
    return essence in RECORD_TYPES or not essence


def _record(method, path, query, req_headers, req_body, status, resp_headers, body):
    cookie = req_headers.get("cookie", "")
    with _lock:
        group = _group_for(cookie, resp_headers.get("set-cookie", ""))
        _seq[group] = _seq.get(group, 0) + 1
        seq = _seq[group]
        name = "%s %s%s #%d" % (method, path, ("?" + query) if query else "", len(_cases) + 1)
        _cases.append({
            "name": name,
            "group": group,
            "seq": seq,
            # The legacy file this exercises. The server resolves it to the component that
            # reimplemented it, which is what turns "something diverged" into "this
            # component diverged".
            "source_path": path.lstrip("/"),
            "request": {
                "method": method,
                "path": path,
                "query": query,
                "headers": {k: v for k, v in req_headers.items()
                            if k in ("content-type", "accept", "accept-language")},
                "cookies": _parse_cookies(cookie),
                "body": req_body,
                "content_type": req_headers.get("content-type", ""),
            },
            "expected": {
                "status": status,
                "location": resp_headers.get("location", ""),
                "content_type": resp_headers.get("content-type", ""),
                "body": body,
            },
            "source": "proxy",
        })


def _parse_cookies(header):
    out = {}
    for part in (header or "").split(";"):
        if "=" in part:
            k, _, v = part.partition("=")
            out[k.strip()] = v.strip()
    return out


class Handler(http.server.BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"
    target = ""

    def log_message(self, fmt, *args):
        pass

    def _proxy(self):
        parsed = urllib.parse.urlsplit(self.path)
        length = int(self.headers.get("content-length") or 0)
        body = self.rfile.read(length) if length else b""

        url = self.target.rstrip("/") + self.path
        headers = {k: v for k, v in self.headers.items()
                   if k.lower() not in ("host", "accept-encoding", "connection")}
        # Identity encoding: a gzipped body would be recorded as bytes nobody can compare.
        headers["Accept-Encoding"] = "identity"
        request = urllib.request.Request(url, data=body or None, headers=headers,
                                         method=self.command)
        try:
            # Redirects are behaviour, not something to follow: a POST that 302s to the list
            # page is the case. Following it would record the destination and lose the fact
            # that a redirect happened at all.
            opener = urllib.request.build_opener(_NoRedirect)
            with opener.open(request, timeout=60) as response:
                status = response.status
                resp_headers = {k.lower(): v for k, v in response.headers.items()}
                payload = response.read()
        except urllib.error.HTTPError as exc:
            status = exc.code
            resp_headers = {k.lower(): v for k, v in (exc.headers or {}).items()}
            payload = exc.read()
        except Exception as exc:
            self.send_response(502)
            self.end_headers()
            self.wfile.write(("proxy could not reach %s: %s" % (self.target, exc)).encode())
            return

        text = payload.decode("utf-8", "replace")
        if _should_record(parsed.path, resp_headers.get("content-type", "")):
            _record(self.command, parsed.path, parsed.query,
                    {k.lower(): v for k, v in self.headers.items()},
                    body.decode("utf-8", "replace"), status, resp_headers, text)
            sys.stderr.write("  recorded %s %s -> %s\n" % (self.command, self.path, status))

        self.send_response(status)
        for key, value in resp_headers.items():
            if key in ("transfer-encoding", "content-length", "connection"):
                continue
            self.send_header(key, value)
        self.send_header("Content-Length", str(len(payload)))
        self.end_headers()
        self.wfile.write(payload)

    do_GET = do_POST = do_PUT = do_DELETE = do_PATCH = do_HEAD = _proxy


class _NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, *args, **kwargs):
        return None


class _Server(socketserver.ThreadingTCPServer):
    allow_reuse_address = True
    daemon_threads = True


def upload(token, dry_run=False):
    with _lock:
        cases = list(_cases)
    if not cases:
        sys.stderr.write("\nNothing was recorded, so nothing was uploaded.\n")
        return 1
    payload = {"cases": cases, "source": "proxy"}
    if dry_run:
        path = "parity-cases.json"
        with open(path, "w", encoding="utf-8") as handle:
            json.dump(payload, handle, indent=2)
        sys.stderr.write("\n%d case(s) written to %s — nothing was uploaded.\n"
                         % (len(cases), path))
        return 0
    url = "%s/runs/%s/parity-cases" % (API_BASE.rstrip("/"), RUN_ID)
    request = urllib.request.Request(
        url, data=json.dumps(payload).encode("utf-8"), method="POST",
        headers={"Content-Type": "application/json", "X-API-Key": token})
    try:
        with urllib.request.urlopen(request, timeout=120) as response:
            body = json.loads(response.read().decode("utf-8", "replace"))
        sys.stderr.write("\nUploaded %d case(s): %s\n" % (len(cases), json.dumps(body)))
        return 0
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", "replace")
        sys.stderr.write("\nUpload failed (%s): %s\n" % (exc.code, detail[:2000]))
        # The corpus is the expensive part — an afternoon of driving the application. Never
        # lose it to a bad token or a rejected case; write it out so it can be fixed and
        # re-sent with --from-file.
        with open("parity-cases.json", "w", encoding="utf-8") as handle:
            json.dump(payload, handle, indent=2)
        sys.stderr.write("The recording was kept in parity-cases.json.\n")
        return 1


def main():
    parser = argparse.ArgumentParser(description="Record parity cases from a legacy app.")
    parser.add_argument("--target", required=True,
                        help="Where the legacy application is, e.g. http://localhost:8080")
    parser.add_argument("--port", type=int, default=__LM_PORT__,
                        help="Port to listen on; drive the legacy app through this.")
    parser.add_argument("--token", default="", help="An API key for the platform.")
    parser.add_argument("--dry-run", action="store_true",
                        help="Write parity-cases.json instead of uploading.")
    parser.add_argument("--from-file", default="",
                        help="Upload a previously written parity-cases.json and exit.")
    parser.add_argument("--seconds", type=int, default=0,
                        help="Stop and upload automatically after this many seconds.")
    args = parser.parse_args()

    if args.from_file:
        with open(args.from_file, encoding="utf-8") as handle:
            saved = json.load(handle)
        _cases.extend(saved.get("cases") or [])
        return upload(args.token)
    if not args.token and not args.dry_run:
        parser.error("--token is required unless --dry-run is used.")

    # Ctrl-Break on Windows raises SIGBREAK, whose default action kills the process outright
    # — the recording would be lost after an afternoon of driving the application, which is
    # the one failure this script cannot afford. Turn it into the same orderly stop as
    # Ctrl-C. `--seconds` exists for the same reason from the other end: an unattended
    # capture that ends by itself never depends on a signal at all.
    if hasattr(signal, "SIGBREAK"):
        signal.signal(signal.SIGBREAK,
                      lambda *_: (_ for _ in ()).throw(KeyboardInterrupt()))

    Handler.target = args.target
    server = _Server(("127.0.0.1", args.port), Handler)
    if args.seconds:
        threading.Timer(args.seconds, server.shutdown).start()
    sys.stderr.write(
        "Recording %s\n"
        "Drive the application through http://127.0.0.1:%d and every page is recorded.\n"
        "Include the flows that fail as well as the ones that work.\n"
        "Ctrl-C to stop and upload.\n\n" % (args.target, args.port))
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.shutdown()
    return upload(args.token, args.dry_run)


if __name__ == "__main__":
    sys.exit(main())
'''


def render_recorder(api_base: str, run_id: str, port: int = 8901) -> str:
    """The capture proxy, bound to one run.

    `api_base` is the platform's `/api/v1/modernization` prefix, fully qualified — the host
    has no configured public address, so only the caller knows how the customer reaches it.
    """
    return (
        _RECORDER_TEMPLATE
        .replace("__LM_API_BASE__", _literal(api_base, "api_base", require_url=True))
        .replace("__LM_RUN_ID__", _literal(run_id, "run_id"))
        .replace("__LM_PORT__", str(int(port)))
    )


