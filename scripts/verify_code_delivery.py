"""Push generated code to a real repository, through the real route, and check what landed.

    python scripts/verify_code_delivery.py https://github.com/owner/scratch-repo
    python scripts/verify_code_delivery.py <url> --dry-run   # every refusal, no write
    python scripts/verify_code_delivery.py <url> --cleanup   # remove the branches and PRs

**This writes to a real repository. Use a scratch one.** It calls **no model** and spends
nothing: the "generated" files are fabricated here, because the thing under test is the
delivery, not the generation.

It exists for the reason `verify_fix_apply.py` exists, and the reason is not caution — it
is a measured record. Fix delivery had **three** defects that no offline test could see, and
they hid for a structural reason: every offline test of a write path stops before writing
(D-317). `create_branch` given a sha instead of a branch name 404'd every time, so two
deliveries had never once worked (D-314); a base branch derived from a pull request's title
produced a bare 422 (D-315); the same split returned a repository *name* for a repo whose
label had no `@` in it (D-364). All three were found by reading code or by running this
class of script, never by a unit test.

`code_delivery` is a **new** writer, so it starts with exactly that exposure. What is
checked here is what the offline suite structurally cannot reach:

  refusals   every guard that must fire before a byte is written, against real GitHub
  branch     a real branch, cut from the real default branch, with the files actually on it
  pr         a real pull request, with the review status in its body where a merger sees it
  existing   the same delivery a second time -- refused, not silently stacked

The refusal stage runs first and writes nothing, so a broken guard is found before a write
rather than after one.
"""
import argparse
import os
import sys
import uuid

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

PASSED = 0
FAILED = 0


def section(title):
    print()
    print(title)
    print("-" * (len(title) + 1))


def check(label, ok, detail=""):
    global PASSED, FAILED
    if ok:
        PASSED += 1
        print(f"  PASS  {label}")
    else:
        FAILED += 1
        print(f"  FAIL  {label}")
    if detail:
        for line in str(detail).splitlines()[:8]:
            print(f"        {line}")


# Deliberately unremarkable content. A delivery that only works for a one-line file is not
# a working delivery, so this has a nested path, a dot-file and a non-ASCII character.
def _files(tag):
    return [
        {"path": "src/app.py",
         "content": f"# generated by verify_code_delivery {tag}\nprint('hello')\n"},
        {"path": "src/pkg/util.py", "content": "def helper():\n    return 1\n"},
        {"path": ".gitignore", "content": "__pycache__/\n"},
        {"path": "README.md", "content": f"# Scratch delivery {tag}\n\nCafé — non-ASCII.\n"},
    ]


def cleanup(gh, owner, repo, prefix="lm-scaffold/verify-"):
    """Remove what this script created. A pull request can only be closed, not deleted."""
    import httpx
    removed = []
    with httpx.Client(headers=gh.headers, timeout=30) as client:
        refs = client.get(f"{gh.BASE_URL}/repos/{owner}/{repo}/git/matching-refs/heads/{prefix}")
        for ref in (refs.json() if refs.is_success else []):
            branch = ref["ref"].replace("refs/heads/", "")
            prs = client.get(f"{gh.BASE_URL}/repos/{owner}/{repo}/pulls",
                             params={"state": "open", "head": f"{owner}:{branch}"})
            for pr in (prs.json() if prs.is_success else []):
                r = client.patch(f"{gh.BASE_URL}/repos/{owner}/{repo}/pulls/{pr['number']}",
                                 json={"state": "closed"})
                removed.append(f"closed PR #{pr['number']} -> {r.status_code}")
            r = client.delete(f"{gh.BASE_URL}/repos/{owner}/{repo}/git/refs/heads/{branch}")
            removed.append(f"branch {branch} -> {r.status_code}")
    print("Cleanup:")
    for line in removed or ["  nothing to remove"]:
        print(f"  {line}")
    return 0


def main():
    global FAILED
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("url", help="A GitHub repository URL to deliver into. Use a scratch one.")
    ap.add_argument("--dry-run", action="store_true",
                    help="Run only the refusals. Writes nothing.")
    ap.add_argument("--cleanup", action="store_true",
                    help="Remove the branches and pull requests this script created.")
    args = ap.parse_args()

    from backend.services import code_delivery, source_bundle
    owner, repo = code_delivery.owner_repo(args.url)
    gh = source_bundle.github_for_repo(args.url, None)
    if not getattr(gh, "token", ""):
        print("No GitHub token. Set GITHUB_TOKEN, or save a credential for the project.")
        return 2
    if args.cleanup:
        return cleanup(gh, owner, repo)

    from backend import config, database
    from fastapi.testclient import TestClient
    import backend.main as main_mod

    tag = uuid.uuid4().hex[:8]
    print(f"Repository : {owner}/{repo}")
    print(f"Tag        : {tag}")
    print(f"Mode       : {'dry run — refusals only' if args.dry_run else 'REAL — this writes'}")

    with TestClient(main_mod.app) as client:
        login = client.post("/api/auth/login",
                            json={"username": "admin", "password": config.DEFAULT_ADMIN_PASSWORD})
        if login.status_code != 200:
            print(f"Could not sign in: {login.text[:200]}")
            return 2
        H = {"Authorization": f"Bearer {login.json()['token']}"}

        # A stored run of each deliverable type, written straight to the database. No model
        # is called: the generation is not what is under test, and paying for a scaffold to
        # test a `git push` would be a strange way to spend money.
        unreviewed = database.save_review(
            review_type="codegen_scaffold", project_name=f"verify-{tag}",
            input_summary="verify_code_delivery", input_content="",
            result={"project_name": f"verify-{tag}", "files": _files(tag),
                    "summary": "A fabricated scaffold, for verifying delivery."})
        reviewed = database.save_review(
            review_type="migration_execute", project_name=f"verify-{tag}",
            input_summary="verify_code_delivery", input_content="",
            result={"project_name": f"verify-{tag}", "files": _files(tag + "-b"),
                    "summary": "A fabricated migration, for verifying delivery.",
                    "governance_review": {"gate_status": "Green", "findings": [],
                                          "code_review": {"gate_status": "Green"},
                                          "sensitive_data_scan": {"gate_status": "Green"}}})
        not_deliverable = database.save_review(
            review_type="requirement", project_name=f"verify-{tag}",
            input_summary="verify_code_delivery", input_content="", result={"findings": []})

        def deliver(review_id, **body):
            body.setdefault("github_repo_url", args.url)
            return client.post(f"/api/reviews/{review_id}/deliver-code", json=body, headers=H)

        # ── Every guard, against real GitHub, before anything is written ──
        section("refusals — checked against the real repository, writing nothing")

        r = deliver(not_deliverable)
        check("a run that produces no code cannot be delivered", r.status_code == 404,
              f"{r.status_code} {r.text[:160]} -- deny by default: `_DELIVERABLE_RUNS` is a "
              "list of review types, not a guess from the shape of `result`")

        r = deliver(str(uuid.uuid4()))
        check("...nor can a review id that does not exist", r.status_code == 404,
              f"{r.status_code} {r.text[:160]}")

        default_branch = gh.get_default_branch(owner, repo)
        r = deliver(unreviewed, branch=default_branch)
        check("...nor onto the branch it would be merged into", r.status_code == 400,
              f"{r.status_code} {r.text[:200]} -- generated code goes somewhere a person "
              "can read it first; this is the delivery `fix_apply` has and this must not")

        r = deliver(unreviewed, branch="not a branch name")
        check("...nor to a branch name git would not take", r.status_code == 400,
              f"{r.status_code} {r.text[:160]}")

        r = deliver(unreviewed, github_repo_url="https://example.com/not/github")
        check("...nor to something that is not a GitHub repository URL", r.status_code == 400,
              f"{r.status_code} {r.text[:160]}")

        if args.dry_run:
            print()
            print("=" * 78)
            print("Nothing was written to GitHub.")
            print(f"\n{PASSED} passed, {FAILED} failed")
            return 1 if FAILED else 0

        # ── A real branch ────────────────────────────────────────────────
        section(f"branch — a real write to {owner}/{repo}")

        branch_a = f"lm-scaffold/verify-{tag}"
        r = deliver(unreviewed, branch=branch_a)
        check("the delivery completed", r.status_code == 200, f"{r.status_code} {r.text[:300]}")
        body = r.json() if r.status_code == 200 else {}
        check("...committing every file it was given",
              len(body.get("files_committed") or []) == 4 and not body.get("files_failed"),
              f"committed {body.get('files_committed')} failed {body.get('files_failed')}")
        check("THE BRANCH EXISTS ON GITHUB", gh.branch_exists(owner, repo, branch_a),
              f"{branch_a} -- this is the check D-314 needed and no offline test could make")
        check("...cut from the repository's own default branch, not a guessed 'main'",
              body.get("base_branch") == default_branch,
              f"{body.get('base_branch')!r} vs {default_branch!r}")
        check("...and no pull request was opened, because none was asked for",
              body.get("pull_request") is None, str(body.get("pull_request")))

        import httpx
        with httpx.Client(headers=gh.headers, timeout=30) as hc:
            got = hc.get(f"{gh.BASE_URL}/repos/{owner}/{repo}/contents/src/pkg/util.py",
                         params={"ref": branch_a})
            check("...and a nested path is really on the branch, with its content",
                  got.is_success, f"{got.status_code} for src/pkg/util.py on {branch_a}")

        r = deliver(unreviewed, branch=branch_a)
        check("delivering the same run twice is refused, not stacked", r.status_code == 400,
              f"{r.status_code} {r.text[:200]} -- re-running a generation is cheap and easy "
              "to do twice; a second generation committed on top of the first is not "
              "something a person can see before it happens")

        # ── A real pull request ──────────────────────────────────────────
        section(f"pr — a real write to {owner}/{repo}")

        branch_b = f"lm-scaffold/verify-{tag}-pr"
        r = deliver(reviewed, branch=branch_b, open_pr=True)
        check("the delivery completed", r.status_code == 200, f"{r.status_code} {r.text[:300]}")
        body = r.json() if r.status_code == 200 else {}
        pr = body.get("pull_request") or {}
        check("A PULL REQUEST WAS OPENED", bool(pr.get("url")), str(body)[:300])
        if pr.get("url"):
            print(f"        {pr['url']}")
        check("...against the repository's default branch",
              body.get("base_branch") == default_branch,
              f"{body.get('base_branch')!r} vs {default_branch!r}")

        if pr.get("number"):
            with httpx.Client(headers=gh.headers, timeout=30) as hc:
                got = hc.get(f"{gh.BASE_URL}/repos/{owner}/{repo}/pulls/{pr['number']}")
                text = (got.json() or {}).get("body", "") if got.is_success else ""
            check("...and its body states what reviewed the code",
                  "Review status" in text and "Reviewed by the platform" in text,
                  f"{text[:220]!r} -- whoever merges generated code should not have to work "
                  "out whether anything read it")
            check("...and says plainly that nothing here was compiled or run",
                  "compiled or executed" in text, f"{text[:220]!r}")

        # ── The audit trail ──────────────────────────────────────────────
        section("the audit trail")
        rows = client.get("/api/audit?limit=200&event_type=generated_code_delivered",
                          headers=H)
        check("the audit listing answers at all", rows.status_code == 200,
              f"{rows.status_code} {rows.text[:160]} -- a 404 here reads as an empty trail, "
              "which looks identical to the audit write being broken")
        events = rows.json().get("events", []) if rows.status_code == 200 else []
        check("every attempted write is on the audit trail", len(events) >= 2,
              f"{len(events)} `generated_code_delivered` event(s) -- recorded *before* the "
              "write, because an attempted write to a customer's repository is itself the "
              "event and a failure that leaves no record is worse than a failure")
        check("...naming the repository and the branch",
              any(f"{owner}/{repo}" in (e.get("details") or "") for e in events),
              str([e.get("details") for e in events[:2]])[:300])

    print()
    print("=" * 78)
    print("Created:")
    print(f"  branch         https://github.com/{owner}/{repo}/tree/lm-scaffold/verify-{tag}")
    print(f"  branch + PR    https://github.com/{owner}/{repo}/tree/lm-scaffold/verify-{tag}-pr")
    print()
    print("Remove them with:")
    print(f"  python scripts/verify_code_delivery.py {args.url} --cleanup")
    print()
    print(f"{PASSED} passed, {FAILED} failed")
    return 1 if FAILED else 0


if __name__ == "__main__":
    sys.exit(main())
